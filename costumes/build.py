#!/usr/bin/env python3
"""Turn the costume designs in sets/*.py into hl5_core/src/costume_sets.rs.

    python costumes/build.py            # write the Rust table
    python costumes/build.py --check    # exit 1 if it is stale

The designs are the source of truth and they are OURS: overlay grids drawn on
top of a layer the game ships (for a head costume, img0/000 — the bare head).
The game's own pixels never enter this repository; hl5_core composites the
overlay onto the archive's sheet at boot and serves the result as a host
shadow (hl5_core::costume). This script only transcribes.

Grid rules (shared with atelier.py, which previews them):
  `.` keeps the base pixel, `-` clears it, any other char is a colour from
  COLOURS. `at` is where the grid's top-left lands in the base frame's own
  pixel coordinates (may be negative); base rows above `clear_above` are
  removed before the overlay is drawn. The canvas grows SYMMETRICALLY, because
  the .cif places an image by its centre.

A frame whose index is past the base sheet's end is APPENDED, drawn on the
base image `src` names — the avatar rig's pose images (costumes/rig.py). A
costume with RIG = True carries them, and the rig's cif remaps
(costumes/rig_table.txt, written by astra_studio.py build) are transcribed
here too, so the phone animates it the way the previews do.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "hl5_core" / "src" / "costume_sets.rs"

LAYER_BASE = {i: f"c/sp/img{i}/000.mgr" for i in range(4)}
RIG_TABLE = HERE / "rig_table.txt"


def rgb565(h):
    h = h.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return c ^ 1 if c == 0xF81F else c


def load(slug):
    mod = {}
    exec((HERE / "sets" / f"{slug}.py").read_text(encoding="utf-8"), mod)
    return mod


def catalog():
    rows = []
    for line in (HERE / "catalog.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cid, layer, sheet, slug = line.split()
        rows.append((int(cid), int(layer), int(sheet), slug))
    return rows


def rig_table():
    """(head count, body count, [(anim, dir, frame, layer, from, to)])."""
    counts, rows = {}, []
    for line in RIG_TABLE.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        words = line.split()
        if words[0] in ("head", "body"):
            counts[words[0]] = int(words[1])
        else:
            rows.append(tuple(int(w) for w in words))
    return counts["head"], counts["body"], rows


def lit(s):
    return "&[" + ", ".join(f"0x{b:02x}" for b in s) + "]"


def emit():
    head_count, body_count, remaps = rig_table()
    out = [
        "// @generated by costumes/build.py from costumes/sets/*.py — do not edit.",
        "// The designs are overlays; hl5_core::costume composites them onto the",
        "// archive's own sheet at boot.",
        "",
        "use crate::costume::{Costume, Overlay};",
        "",
        "/// Images in a rigged head sheet (img0): the game's 7, then the poses.",
        f"pub const RIG_HEAD_COUNT: usize = {head_count};",
        "/// Images in a rigged body sheet (img1): the game's 12, then the poses.",
        f"pub const RIG_BODY_COUNT: usize = {body_count};",
        "",
        "/// The rig's cif variant: (anim, dir, frame, layer, image -> image).",
        "/// Applied to a hero cif by `costume::rig_cif`; see costumes/rig.py.",
        "pub const RIG_REMAPS: &[(u8, u8, u8, u8, u8, u8)] = &[",
        *[f"    ({a}, {d}, {f}, {l}, {x}, {y})," for a, d, f, l, x, y in remaps],
        "];",
        "",
        "pub const COSTUMES: &[Costume] = &[",
    ]
    ids, sheets = set(), set()
    for cid, layer, sheet, slug in catalog():
        assert cid not in ids, f"id {cid} twice"
        assert (layer, sheet) not in sheets, f"sheet {layer}/{sheet} twice"
        assert sheet >= 256, f"{slug}: sheet {sheet} < 256"
        ids.add(cid); sheets.add((layer, sheet))
        m = load(slug)
        name = m["NAME"].encode("euc-kr") + b"\0"
        cols = sorted(m["COLOURS"].items())
        used = set()
        frames = []
        rigged = bool(m.get("RIG", False))
        if rigged:
            want = {0: head_count, 1: body_count}[layer]
            first = {0: 7, 1: 12}[layer]
            missing = [i for i in range(first, want) if i not in m["FRAMES"]]
            assert not missing, f"{slug}: rig images {missing} not drawn"
            assert max(m["FRAMES"]) + 1 == want, f"{slug}: rig sheet must end at {want}"
        for idx in sorted(m["FRAMES"]):
            spec = m["FRAMES"][idx]
            grid = spec["grid"]
            for row in grid:
                for ch in row:
                    if ch not in ".-":
                        assert ch in m["COLOURS"], f"{slug} frame {idx}: colour {ch!r}"
                        used.add(ch)
            ox, oy = spec["at"]
            clear = spec.get("clear_above", -999)
            rows = ", ".join('"' + r + '"' for r in grid)
            src = spec.get("src", idx)
            frames.append(
                f"            Overlay {{ index: {idx}, src: {src}, at: ({ox}, {oy}), "
                f"clear_above: {clear}, grid: &[{rows}] }},"
            )
        out += [
            "    Costume {",
            f"        id: {cid},",
            f"        // {m['NAME']}",
            f"        name: {lit(name)},",
            f"        layer: {layer},",
            f"        sheet: {sheet},",
            f'        base: "{m.get("BASE", LAYER_BASE.get(layer, ""))}",',
            f'        classes: {m.get("CLASSES", 15)},',
            f'        hidden_weapon: {str(m.get("HIDDEN_WEAPON", False)).lower()},',
            f'        rig: {str(rigged).lower()},',
            f'        fx: {int(m.get("FX", 0))},',
            "        recolour: &["
            + ", ".join(f"(0x{a:04x}, 0x{b:04x})" for a, b in sorted((m.get("RECOLOUR") or {}).get("map", {}).items()))
            + "],",
            "        keep: &[" + ", ".join(str(k) for k in (m.get("RECOLOUR") or {}).get("keep", [])) + "],",
            "        colours: &["
            + ", ".join(f"(b'{k}', 0x{rgb565(v):04x})" for k, v in cols)
            + "],",
            "        frames: &[",
            *frames,
            "        ],",
            "    },",
        ]
    out += ["];", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = emit()
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur != text:
            print(f"{OUT} is stale; run python costumes/build.py")
            sys.exit(1)
        print("costume_sets.rs is current")
    else:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT} ({len(catalog())} costume(s))")
