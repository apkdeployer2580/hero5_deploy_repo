#!/usr/bin/env python3
"""Write a full ten-page 공용창고 (hl5_warehouse.txt + hl5_warehouse_upper.txt)
into a probe storage directory, for exercising pages 6..10 offline.

    python whfill.py out/tp [--slots 160] [--equip <hex record>] [--all-equip]

Even cells hold an equipment record (default: a real deposit captured from the
guest, kind 5 index 1); odd cells hold a stack of orbs (kind 12, index = page
mod 14, count = slot mod 99 + 1) so the stack-count array — the part of the
object the ten-page rewrite moves — shows a different number in every cell.

`--all-equip` puts the equipment record in every cell instead. That is the
*big* listing: an equipment record is 78 bytes and an orb stack 10, so the
default fill's `4/6` frame is 7.9 KB — just under the 8 KB the shipped guest
copies a frame into — while 160 equipment items make it 13.3 KB. The default
fill is how ANALYSIS.md §65 passed while every warehouse past 90 equipment
items crashed or lost records (§65.14); use this one to test the receive path.
"""
import argparse
from pathlib import Path

EQUIP = ("0000000105010000000ab3aac0ccc6aeb1e2beee0000000000000000000000000000000000"
         "00000000000003006c004e0105000500030011000600ff00ff00ff0000000000ffffffffff00050003")

def short(count, kind, index):
    return count.to_bytes(4, "big") + bytes([kind, index]) + (0).to_bytes(4, "big")

ap = argparse.ArgumentParser()
ap.add_argument("storage", type=Path)
ap.add_argument("--slots", type=int, default=160)
ap.add_argument("--equip", default=EQUIP)
ap.add_argument("--all-equip", action="store_true", help="equipment in every cell (§65.14)")
a = ap.parse_args()
lower = ["# hl5 warehouse v1 — generated by tools_re/whfill.py", "capacity 80", "money 0"]
upper = ["# hl5 warehouse pages 6-10 — generated by tools_re/whfill.py", "capacity 160"]
listing = 20 + 12  # the frame header, then [i32 result][u32 0][i32 count]
for n in range(a.slots):
    page, cell = divmod(n, 16)
    equip = a.all_equip or cell % 2 == 0
    rec = bytes.fromhex(a.equip) if equip else short(n % 99 + 1, 12, page % 14)
    (lower if n < 80 else upper).append(f"slot {n} state 0 item {rec.hex()}")
    listing += 5 + len(rec)
listing += (160 - a.slots) * 9  # the empty slots a ten-page listing still sends
a.storage.mkdir(parents=True, exist_ok=True)
(a.storage / "hl5_warehouse.txt").write_text("\n".join(lower) + "\n", encoding="utf-8")
if a.slots > 80:
    (a.storage / "hl5_warehouse_upper.txt").write_text("\n".join(upper) + "\n", encoding="utf-8")
print(f"{a.slots} slots written under {a.storage}; ten-page 4/6 frame {listing} B "
      f"(shipped receive buffer 8192 B)")
