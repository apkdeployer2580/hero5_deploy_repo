// ---- 창고접속 without a server ------------------------------------------------
//
// Picking 창고접속 offline used to bounce the player out with
// `서버상태가 좋지 않습니다 … (302)`. The cause was **not** a failed connect —
// the socket opens, `1/1` and `1/5` are answered, and then the guest asks
// `1/3` (its own nickname) and nothing answers, so
// `NETWORK::CheckServerConnectLimitTime` fires 5,912 ms later and destroys
// `StateNetMenu` (ANALYSIS.md §31.5, reproduced and refined below).
//
// The fix needs no guest hook at all, and that is the whole point: **the guest
// raises its own one-button popup carrying whatever message the server sends**.
// Every `ProcPacket_*` reachable from this menu has the same shape —
// `readNet32` into `NETWORK+0x368`, `readNetBuf` into `NETWORK+0x36C`, and
// `result != 0` goes to `NETWORK::CreateMessagePopup(NETWORK+0x36C)`. So
// "이 기능은 이용할 수 없습니다" is a *reply*, not a UI change.
//
// Two frames have to be answered for the menu to open at all, and both were
// measured rather than guessed:
//
// * **`1/3`** — the nickname. `ProcPacket_Login`'s subcmd-3 arm reads
//   `[i32 result][blob message]`, and on `result == 0` reads a third blob and
//   `memcpy`s 15 bytes of it to `NETWORK+0x359` (`GetNickNamePtr`).
// * **`7/1`** — a notice. `ProcPacket_Notice` (0xC84EC) is the one packet with
//   **no silent answer**: `result != 0` pops the message, and `result == 0`
//   memsets a 1,024-byte buffer, reads a *second* blob into it, and pops
//   **that** (+0x84). So something is always shown; this sends the one line
//   worth showing.
//
// Everything else is declined with a message, which is what puts the guest's
// own popup on the item the player actually pressed:
//
// ```text
//   판매거래소 -> 2/3     구매거래소 -> 4/7     창고관리 -> 4/6
//   우편함    -> 8/3     슬롯변경  -> no packet at all (works offline)
//   캐쉬상점  -> local catalogue + `Config::free_shop`
// ```
//
// `0/2` — `SendAlivePacket` — is deliberately left unanswered. `WriteData+0x1c`
// clears `NETWORK+0x0b` and only `PacketWrite_System` sets it, and the
// `WriteData` tail returns on that flag *before* stamping the watchdog clock
// and before `CreatePopup(0x155)`. So the keep-alive neither arms the 5,912 ms
// timer nor shows "Connecting", and four consecutive unanswered ones were
// measured with no error.
//
// # Why 창고관리 is refused rather than opened empty
//
// It *could* be opened: `4/6` answered with `[i32 result][blob msg][i32 cap]`
// plus one `[i32 slot][u8 flag][_NET_ITEM_]` record per slot fills the grid,
// and `capacity` is both the record count and the capacity —
// `StateNetMenu::DrawStorageUI` pages it as `capacity >> 4`, so anything under
// 16 draws an empty grid however many records arrived (that is the unresolved
// item in §31.5, and it is now resolved). An empty slot is exactly
// `[i32 slot][u8 0][i32 0]`.
//
// It is refused anyway, because a warehouse you can put things *into* and that
// forgets them is worse than one that says it is closed: the deposit path is
// `4/10` then `4/11`, and with nothing persisting them an item would be gone
// for good. Opening it read-only would invite exactly that. The recipe above is
// recorded so the working version — which needs a host-side store first — is a
// small step rather than a rediscovery.

