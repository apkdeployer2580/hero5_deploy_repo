    /// Ten pages of equipment outgrow the 8 KB `NETWORK::receiveData` copies
    /// a frame into, unchecked (ANALYSIS.md §65.14). Against that buffer the
    /// listing must be refused, never sent; against the ten-page buffer it
    /// goes out whole. Either way every item stays.
    #[test]
    fn a_listing_the_guest_cannot_hold_is_declined_not_sent() {
        let (wh, _) = Warehouse::load_offering(&tmp("too-big"), crate::tenpages::STORAGE_SLOTS);
        let wh = Arc::new(Mutex::new(wh));
        let mut s = Session::offline(Arc::new(GrantTable::default()), wh.clone());
        // The record `tools_re/whfill.py` deposits: 78 bytes, a 10-byte name.
        let item = net_item(1, 5, 1, b"0123456789");
        assert_eq!(item.len(), 78);
        let listing = |s: &mut Session| {
            s.write(&req(4, 6, &[]));
            let out = s.read(1 << 20);
            (out.len() - 4, frame(&out).2)
        };

        // 90 equipment items: 1,472 + 74 × 90 = 8,132 bytes, inside 8,192.
        for _ in 0..90 {
            assert_eq!(Reader::new(&ask(&mut s, 4, 10, &item)).i32(), 0);
        }
        let (len, f) = listing(&mut s);
        assert_eq!(len, 8132);
        assert_eq!(Reader::new(&f).i32(), 0, "still fits the shipped buffer");

        // The 91st makes it 8,206 — the first count the probe faults on.
        assert_eq!(Reader::new(&ask(&mut s, 4, 10, &item)).i32(), 0);
        let (len, f) = listing(&mut s);
        let mut r = Reader::new(&f);
        assert_ne!(r.i32(), 0, "a frame past the buffer must not go out");
        assert_eq!(r.blob(), MSG_LISTING_TOO_BIG);
        assert!(len < 100, "the refusal is all that was sent");
        assert_eq!(wh.lock().expect("lock").used(), 91, "and nothing was lost");

        // With the ten-page buffer the full warehouse goes out whole.
        s.set_frame_limit(crate::tenpages::RECV_BODY_NEW as usize);
        for _ in 91..160 {
            ask(&mut s, 4, 10, &item);
        }
        let (len, f) = listing(&mut s);
        assert!(len <= crate::tenpages::RECV_BODY_NEW as usize, "{len}");
        let mut r = Reader::new(&f);
        assert_eq!(r.i32(), 0);
        assert!(r.blob().is_empty());
        assert_eq!(r.i32(), 160);
        assert_eq!(f.len(), 12 + 160 * (5 + item.len()), "every record, every byte");
    }

