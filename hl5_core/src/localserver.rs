//! The private server, in-process: "네트워크 없는 캐시샵"'s delivery half.
//!
//! `hl5_server/server.py` is the reference implementation — every handler in
//! it corresponds to an exchange *measured* off the running client
//! (`tools_re/testserver.py`, transcript in `docs/SERVER.md` §6.8), and the
//! deployed instance is what the S25 logged in to over the public internet.
//! This module is that server transcribed to Rust and moved inside the
//! process, so the cash shop's `netConnect` can complete with no network at
//! all: `files.rs` hands a [`Session`] the bytes the guest `send`s and queues
//! what the session answers for the guest's `recv`.
//!
//! # The rule this has to obey
//!
//! **Same bytes as the Python server.** Not "equivalent" — the same bytes,
//! because the guest is the same client either way and the Python side is the
//! implementation that was debugged against it (the reply-opcode-2-not-4
//! lesson, the CrossRoad per-query ack). The acceptance test is
//! `hl5_core/tests/localserver_ab.rs`: `tools_re/gen_localserver_fixtures.py`
//! runs the *actual* `hl5_server` code over a scripted conversation and dumps
//! every request/reply pair; the test replays the requests through [`Session`]
//! and asserts the replies match byte for byte. Change either side without
//! regenerating and the test says so.
//!
//! # The one thing it is allowed to add
//!
//! **Grants.** The deployed server answers 6/5 with zero records, and so does
//! this by default — a [`Session::new`] session is the Python server, full
//! stop, which is what keeps the fixture A/B meaning what it says. Only
//! [`Session::with_grants`], reached when `Config::free_shop` is set, puts
//! real `_NET_ITEM_` records in that packet, and the table it draws them from
//! is derived from the game's own catalogue rather than invented
//! (`shop::GrantTable`, CLAUDE.md "캐시샵을 로컬로"). Everything downstream —
//! `readNetItem`, `NewBagNetItem`, the stacking merge, the 공허-weapon remap —
//! is untouched guest code.

